from __future__ import annotations

from typing import Any, List, Literal, Optional
from pydantic import BaseModel, ConfigDict, Field

# =============================================================================
# Retrieved Context
# =============================================================================

class RetrievedChunk(BaseModel):
    """A single retrieved knowledge chunk."""

    model_config = ConfigDict(extra="forbid")

    company: str = Field(description="Knowledge base source.")
    product_area: str = Field(description="Product area associated with this document.")
    title: str = Field(description="Document title.")
    section: str = Field(description="Section title.")
    url: str = Field(description="Documentation URL.")
    document_id: str = Field(description="Unique document identifier.")
    chunk_id: str = Field(description="Unique chunk identifier.")
    score: float = Field(description="Retrieval score.")
    text: str = Field(description="Retrieved document content.")


# =============================================================================
# Support Ticket
# =============================================================================

class SupportTicket(BaseModel):
    """Customer support ticket."""

    model_config = ConfigDict(extra="forbid")

    issue: str = Field(min_length=1, description="Customer issue description.")
    subject: str = Field(default="", description="Optional ticket subject.")
    company: str = Field(default="", description="Company name.")
    reranker: str = "none"
    search_mode: str = "hybrid"
    top_k: int = 5


# =============================================================================
# Decision Result (Unified Output of LLM #1 Decision Engine)
# =============================================================================

class DecisionResult(BaseModel):
    """
    Unified result object returned by LLM #1 (Decision Engine).
    Carries safety, intent, company detection, and routing decision.
    """

    model_config = ConfigDict(extra="forbid")

    safe: bool = Field(default=True, description="Whether the request is safe.")
    intent: str = Field(default="PRODUCT_SUPPORT", description="Classified intent.")
    company: str = Field(default="", description="Target company/domain.")
    routing_strategy: str = Field(default="SUPPORT_RESPONSE", description="Routing strategy name.")
    retrieval_required: bool = Field(default=True, description="Whether documentation retrieval is required.")
    reason: str = Field(default="", description="Explanation for routing decision.")
    confidence: float = Field(default=1.0, description="Classification confidence score.")
    company_reference_found: bool = Field(default=False, description="Whether explicit company reference was found.")
    routing_status: str = Field(default="NO_COMPANY_REFERENCE",description="COMPANY_VERIFIED, COMPANY_MISMATCH, or NO_COMPANY_REFERENCE.",)
    normalized_issue: str = Field(default="", description="Cleaned issue text.")
    normalized_subject: str = Field(default="", description="Cleaned subject text.")


# =============================================================================
# Structured LLM Response (Output of LLM #2 Generation Engine)
# =============================================================================

class SupportResponse(BaseModel):
    """Final structured response generated by LLM #2 Generation Engine."""

    model_config = ConfigDict(extra="forbid")

    request_type: Literal["product_issue", "feature_request", "bug", "invalid"] = Field(description="Support request classification.")
    product_area: str = Field(description="Most relevant product area.")
    status: Literal["Replied", "Escalated"] = Field(description="Whether the issue was answered or escalated.")
    response: str = Field(description="Customer-facing support response.")
    justification: str = Field(description="Short evidence-based explanation.")


# =============================================================================
# Source Information
# =============================================================================


class SourceDocument(BaseModel):
    """Documentation source used to generate the response."""

    model_config = ConfigDict(extra="forbid")

    company: str
    title: str
    url: str


# =============================================================================
# Public Agent Response
# =============================================================================


class AgentResponse(BaseModel):
    """
    Public output of SupportAgent.invoke().
    Carries the generated response, decision result, retrieval metadata, and execution trace.
    """

    model_config = ConfigDict(extra="allow")

    # -------------------------------------------------------------------------
    # Core response
    # -------------------------------------------------------------------------
    response: SupportResponse
    decision_result: Optional[DecisionResult] = Field(default=None, description="Output object from LLM #1 Decision Engine.")
    sources: list[SourceDocument] = Field(default_factory=list)
    retrieved_context: list[str] = Field(default_factory=list,description="Retrieved document text used to generate the answer.",)
    retrieved_chunks: list[RetrievedChunk] = Field(default_factory=list, description="Retrieved chunks with metadata.")
    num_chunks: int = Field(default=0)
    token_estimate: int = Field(default=0)
    retrieval_trace: dict = Field(default_factory=dict,description="Metadata trace about retrieval execution steps.",)

    # -------------------------------------------------------------------------
    # Decision Engine convenience accessors
    # -------------------------------------------------------------------------
    retrieval_required: bool = Field(default=True)
    normalized_issue: str = Field(default="")
    normalized_subject: str = Field(default="")
    routing_reason: str = Field(default="")
    confidence: float = Field(default=1.0)
    selected_company: str = Field(default="")
    detected_company: Optional[str] = Field(default=None)
    verified_company: str = Field(default="")
    company_match: bool = Field(default=True)
    company_confidence: float = Field(default=1.0)
    classification_confidence: float = Field(default=1.0)
    company_reference_found: bool = Field(default=False)
    routing_status: str = Field(default="NO_COMPANY_REFERENCE")
    reference_confidence: float = Field(default=1.0)
    routing_message: str = Field(default="")
    intent: str = Field(default="PRODUCT_SUPPORT")
    routing_strategy: str = Field(default="SUPPORT_RESPONSE")
    response_strategy: str = Field(default="SUPPORT_RESPONSE")

    # -------------------------------------------------------------------------
    # Token usage for billing
    # -------------------------------------------------------------------------
    decision_input_tokens: int = Field(default=0)
    decision_output_tokens: int = Field(default=0)
    generation_input_tokens: int = Field(default=0)
    generation_output_tokens: int = Field(default=0)

    # -------------------------------------------------------------------------
    # Execution flags
    # -------------------------------------------------------------------------
    blocked: bool = Field(default=False)
    regenerated: bool = Field(default=False)
    retriever_used: bool = Field(default=False)
    llm_used: bool = Field(default=False)
    template_used: bool = Field(default=False)
    decision_latency_ms: float = Field(default=0.0)
    generation_latency_ms: float = Field(default=0.0)
    retrieval_latency_ms: float = Field(default=0.0)

    # -------------------------------------------------------------------------
    # Execution Trace — single source of truth for observability
    # -------------------------------------------------------------------------
    execution_trace: List[dict] = Field(default_factory=list,description="Ordered list of StageRecord dicts — one per pipeline stage.",)

    warnings: list[str] = Field(default_factory=list)


